function prm = mkparam(val, unit, status, src, gap, mref)
prm = struct('v', [], 'unit', unit, 'status', status, 'src', src, 'gap', gap, 'model_ref', mref);
prm.v = val;
end

function [v, ok] = getp(P, ref)
parts = strsplit(ref, '.');
v = P;
ok = true;
for k = 1:numel(parts)
    if isstruct(v) && isfield(v, parts{k})
        v = v.(parts{k});
    else
        v = [];
        ok = false;
        return
    end
end
end

function L = leaves(S, prefix)
L = {};
f = fieldnames(S);
for k = 1:numel(f)
    name = f{k};
    if isempty(prefix), p = name; else, p = [prefix '.' name]; end
    v = S.(name);
    if isstruct(v) && isscalar(v)
        L = [L, leaves(v, p)]; %#ok<AGROW>
    else
        L{end+1} = p; %#ok<AGROW>
    end
end
end
